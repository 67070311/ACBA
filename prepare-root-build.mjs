// Compatibility entrypoint for Vercel projects configured at the repository root.
// Keep all application source and public assets inside my-app.
import { cpSync, existsSync, lstatSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL(".", import.meta.url));
const marker = join(root, ".acba-root-generated");
const folders = ["app", "public"];
for (const folder of folders) {
  const target = join(root, folder);
  if (existsSync(target) && (!existsSync(marker) || !lstatSync(target).isDirectory() || lstatSync(target).isSymbolicLink())) {
    throw new Error("Refusing to overwrite unmanaged root directory: " + folder);
  }
}
writeFileSync(marker, "Generated by prepare-root-build.mjs\n");
for (const folder of folders) {
  const target = join(root, folder);
  rmSync(target, { recursive: true, force: true });
  cpSync(join(root, "my-app", folder), target, { recursive: true });
}
